char	*ft_strupcase(char *str)
{
	int	dif;
	int	i;

	dif = 'a' - 'A';
	i = 0;
	while (str[i] != '\0')
	{
		if (str[i] >= 'a' && str[i] <= 'z')
		{
			str[i] = str[i] - dif;
		}
		i++;
	}
	return (str);
}
